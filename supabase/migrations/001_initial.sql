begin;
create table if not exists public.pl_classes(name text primary key check(length(name) between 1 and 60),schedule text not null default '' check(schedule in ('','MWF','TTS')));
create table if not exists public.pl_students(id bigint generated by default as identity primary key,name text not null check(length(name) between 1 and 60),phone text unique not null check(phone ~ '^010[0-9]{8}$'),class_name text not null references public.pl_classes(name),active boolean not null default true);
create table if not exists public.pl_videos(id text primary key check(id ~ '^[A-Za-z0-9_-]{11}$'),title text not null,class_name text not null default '',book text not null default '',subject text not null default '',unit text not null default '',added_at double precision not null,timeline jsonb not null default '[]',published boolean not null default false,reviewed boolean not null default false,timeline_draft jsonb,notes text not null default '',supplement_needed boolean not null default false);
create table if not exists public.pl_video_classes(video_id text not null references public.pl_videos(id) on delete cascade,class_name text not null references public.pl_classes(name),primary key(video_id,class_name));
create table if not exists public.pl_favorites(student_id bigint not null references public.pl_students(id) on delete cascade,video_id text not null references public.pl_videos(id) on delete cascade,primary key(student_id,video_id));
create table if not exists public.pl_sessions(digest text primary key,student_id bigint references public.pl_students(id) on delete cascade,role text not null check(role in ('student','teacher')),expires double precision not null,check((role='teacher' and student_id is null) or (role='student' and student_id is not null)));
create table if not exists public.pl_settings(key text primary key,value jsonb not null);
create table if not exists public.pl_rate_limits(key text primary key,attempts integer not null,expires double precision not null);
create index if not exists pl_students_class_idx on public.pl_students(class_name);
create index if not exists pl_video_class_idx on public.pl_video_classes(class_name,video_id);
create index if not exists pl_sessions_expiry_idx on public.pl_sessions(expires);
create index if not exists pl_sessions_student_idx on public.pl_sessions(student_id);

-- Browser roles have no direct access. The same-origin application server checks each session.
do $$ declare t text; begin
 foreach t in array array['classes','students','videos','video_classes','favorites','sessions','settings','rate_limits'] loop
  execute format('alter table public.%I enable row level security','pl_'||t);
  execute format('revoke all on public.%I from anon,authenticated','pl_'||t);
  execute format('grant select,insert,update,delete on public.%I to service_role','pl_'||t);
 end loop;
end $$;
grant usage,select on sequence public.pl_students_id_seq to service_role;
revoke all on sequence public.pl_students_id_seq from anon,authenticated;

create or replace function public.pl_save_video(p_video jsonb,p_classes jsonb) returns void
language plpgsql set search_path=public,pg_temp as $$
declare g text; begin
 insert into pl_videos(id,title,class_name,book,subject,unit,added_at,timeline,published,reviewed,timeline_draft,notes,supplement_needed)
 values(p_video->>'id',p_video->>'title',coalesce(p_video->>'class_name',''),coalesce(p_video->>'book',''),coalesce(p_video->>'subject',''),coalesce(p_video->>'unit',''),(p_video->>'added_at')::double precision,coalesce(p_video->'timeline','[]'),(p_video->>'published')::boolean,(p_video->>'reviewed')::boolean,nullif(p_video->'timeline_draft','null'),coalesce(p_video->>'notes',''),(p_video->>'supplement_needed')::boolean)
 on conflict(id) do update set title=excluded.title,class_name=excluded.class_name,book=excluded.book,subject=excluded.subject,unit=excluded.unit,published=excluded.published;
 delete from pl_video_classes where video_id=p_video->>'id';
 for g in select jsonb_array_elements_text(p_classes) loop
  insert into pl_classes(name) values(g) on conflict do nothing;
  insert into pl_video_classes values(p_video->>'id',g);
 end loop;
end $$;

create or replace function public.pl_save_student(p_student jsonb) returns jsonb
language plpgsql set search_path=public,pg_temp as $$
declare old pl_students; result pl_students; begin
 if p_student->>'id' is not null then
  select * into strict old from pl_students where id=(p_student->>'id')::bigint for update;
  update pl_students set name=p_student->>'name',phone=p_student->>'phone',class_name=p_student->>'class_name',active=(p_student->>'active')::boolean where id=old.id returning * into result;
  if old.phone<>result.phone or not result.active then delete from pl_sessions where student_id=result.id; end if;
 else
  insert into pl_students(name,phone,class_name,active) values(p_student->>'name',p_student->>'phone',p_student->>'class_name',(p_student->>'active')::boolean) returning * into result;
 end if;
 return to_jsonb(result);
end $$;

create or replace function public.pl_consume_rate(p_key text,p_limit integer,p_seconds integer) returns boolean
language plpgsql set search_path=public,pg_temp as $$
declare n integer; now_s double precision:=extract(epoch from clock_timestamp()); begin
 if p_limit<1 or p_limit>1000 or p_seconds<1 or p_seconds>86400 then raise exception 'invalid rate limit'; end if;
 delete from pl_rate_limits where expires<now_s;
 insert into pl_rate_limits values(p_key,1,now_s+p_seconds)
 on conflict(key) do update set attempts=pl_rate_limits.attempts+1 returning attempts into n;
 return n<=p_limit;
end $$;
revoke all on function public.pl_save_video(jsonb,jsonb),public.pl_save_student(jsonb),public.pl_consume_rate(text,integer,integer) from public,anon,authenticated;
grant execute on function public.pl_save_video(jsonb,jsonb),public.pl_save_student(jsonb),public.pl_consume_rate(text,integer,integer) to service_role;
commit;
